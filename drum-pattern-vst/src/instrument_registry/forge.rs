//! Percussion Forge metadata. Numeric source controls remain continuous.
use super::*;

macro_rules! standard {
    ($name:ident, $freq_label:literal, $min:expr, $max:expr, $decay_label:literal, $dmin:expr, $dmax:expr $(, $stereo:ident)?) => {
        const $name: &[StandardParamDef] = &[
            s(StandardField::Freq, $freq_label, ParamFamily::Osc, $min, $max, false, Some(" Hz")),
            s(StandardField::Decay, $decay_label, ParamFamily::Env, $dmin, $dmax, false, Some(" s")),
            // Shared Volume displays 0..1 but persists 0..2 on every lane.
            s(StandardField::Volume, "Volume", ParamFamily::Output, 0.0, 2.0, false, None),
            $(cb(StandardField::$stereo, "Stereo", ParamFamily::Stereo),)?
        ];
    };
}
