//! Embedded sample data: the TR-606 multisample banks (8 hits each) and the
//! long Rift textures ([221]).
//!
//! Each WAV (float32 mono, 44.1 kHz) holds the 8 hits back to back at even
//! spacing. Files are embedded with `include_bytes!` and decoded once into
//! global `OnceLock`s. Playback handles the session sample-rate conversion
//! through fractional-position interpolation, so no resampling pass is
//! needed at load time.
//!
//! A **texture** ([221]) is the other shape the same decoder serves: one
//! continuous buffer of several seconds instead of eight slices, which Rift
//! reads from an arbitrary offset. Same embedding, same `OnceLock`, same
//! fractional-position playback — only the splitting differs, so the RIFF
//! parser is shared (`decode_wav`).
//!
//! Real-time contract: banks and textures must be pre-warmed from
//! `DrumSynthesizer::initialize_with_layout` (non-RT). After that, calls from
//! the audio thread are a single atomic load — no allocation, no lock.

use std::sync::{Arc, OnceLock};

pub const HIT_COUNT: usize = 8;

static BD606_BYTES: &[u8] = include_bytes!("../../assets/bd606.wav");
static SD606_BYTES: &[u8] = include_bytes!("../../assets/sd606.wav");
static CH606_BYTES: &[u8] = include_bytes!("../../assets/ch606.wav");
static OH606_BYTES: &[u8] = include_bytes!("../../assets/oh606.wav");

pub struct SampleBank {
    pub source_rate: f32,
    pub hits: [Vec<f32>; HIT_COUNT],
}

static BD606_BANK: OnceLock<SampleBank> = OnceLock::new();
static SD606_BANK: OnceLock<SampleBank> = OnceLock::new();
static CH606_BANK: OnceLock<SampleBank> = OnceLock::new();
static OH606_BANK: OnceLock<SampleBank> = OnceLock::new();

/// TR-606 bass drum bank (8 × 1 s hits).
pub fn bd606() -> &'static SampleBank {
    BD606_BANK.get_or_init(|| load_bank(BD606_BYTES))
}

/// TR-606 snare bank (8 × 0.5 s hits).
pub fn sd606() -> &'static SampleBank {
    SD606_BANK.get_or_init(|| load_bank(SD606_BYTES))
}

/// TR-606 closed hi-hat bank (8 × 0.5 s hits).
pub fn ch606() -> &'static SampleBank {
    CH606_BANK.get_or_init(|| load_bank(CH606_BYTES))
}

/// TR-606 OPEN hi-hat bank (8 × 1 s hits — an open hat rings longer, so the
/// slices are twice as long as the closed one's).
pub fn oh606() -> &'static SampleBank {
    OH606_BANK.get_or_init(|| load_bank(OH606_BYTES))
}

/// [247] Single source for "which bank does this sampler voice play", shared
/// by the DSP (`DrumSynthesizer`) and the Sound Editor waveform graph.
/// Indices are `DrumVoice` discriminants, kept in sync with
/// `instrument_registry::is_sampler` (13 | 14 | 15 | 24).
pub fn sampler_bank(voice_idx: usize) -> Option<&'static SampleBank> {
    match voice_idx {
        13 => Some(bd606()),
        14 => Some(sd606()),
        15 => Some(ch606()),
        24 => Some(oh606()),
        _ => None,
    }
}

