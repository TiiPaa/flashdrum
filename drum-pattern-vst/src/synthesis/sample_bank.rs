/// Embedded textures (banks). The Texture MENU has one more entry, Custom, in
/// the middle of them: see `CUSTOM_TEXTURE_INDEX`.
pub const TEXTURE_COUNT: usize = 5;

/// Generated by `tools/gen_textures.py` (fixed seed, so re-running it
/// reproduces these files byte for byte). Mono PCM 16-bit, 44.1 kHz, 6 s —
/// half the weight of the float32 606 banks for the same duration.
static TEXTURE_BYTES: [&[u8]; TEXTURE_COUNT] = [
    include_bytes!("../../assets/textures/noise-field.wav"),
    include_bytes!("../../assets/textures/metal.wav"),
    include_bytes!("../../assets/textures/crackle.wav"),
    include_bytes!("../../assets/textures/sweep.wav"),
    include_bytes!("../../assets/textures/pad.wav"),
];

/// Columns in the drawn waveform summary. The Sound Panel graph is ~200 px
/// wide, so this is already finer than it can show.
pub const TEXTURE_PEAK_COLUMNS: usize = 512;

/// One long buffer to read from at an arbitrary offset, as opposed to
/// `SampleBank`'s eight fixed slices.
pub struct TextureBank {
    pub source_rate: f32,
    /// The material: mono, or the LEFT channel of a stereo user file.
    pub data: Vec<f32>,
    /// [228] The RIGHT channel of a stereo user file, same length as `data`;
    /// `None` for mono files and every embedded texture. With Rift's Stereo
    /// switch off the two are mixed at read time.
    pub right: Option<Vec<f32>>,
    /// (min, max) per column — the waveform the panel draws. Computed once at
    /// decode time: scanning half a million samples on every UI frame would
    /// cost far more than the picture is worth.
    pub peaks: Vec<(f32, f32)>,
}

fn peak_summary(data: &[f32]) -> Vec<(f32, f32)> {
    if data.is_empty() {
        return vec![(0.0, 0.0); TEXTURE_PEAK_COLUMNS];
    }
    (0..TEXTURE_PEAK_COLUMNS)
        .map(|c| {
            let from = c * data.len() / TEXTURE_PEAK_COLUMNS;
            let to = ((c + 1) * data.len() / TEXTURE_PEAK_COLUMNS).max(from + 1);
            let slice = &data[from..to.min(data.len())];
            let lo = slice.iter().cloned().fold(f32::MAX, f32::min);
            let hi = slice.iter().cloned().fold(f32::MIN, f32::max);
            (lo, hi)
        })
        .collect()
}

static TEXTURE_BANKS: [OnceLock<TextureBank>; TEXTURE_COUNT] =
    [const { OnceLock::new() }; TEXTURE_COUNT];

/// Texture `index`, clamped into range — an out-of-range index must yield a
/// usable texture, never a panic on the audio thread.
pub fn texture(index: usize) -> &'static TextureBank {
    let i = index.min(TEXTURE_COUNT - 1);
    TEXTURE_BANKS[i].get_or_init(|| {
        let (source_rate, data) = decode_wav(TEXTURE_BYTES[i]);
        let peaks = peak_summary(&data);
        TextureBank {
            source_rate,
            data,
            right: None,
            peaks,
        }
    })
}

/// Decode every texture. Call from `initialize_with_layout` only (non-RT):
/// `create_voice_for_kind` runs on the audio thread and must not allocate.
pub fn prewarm_textures() {
    for i in 0..TEXTURE_COUNT {
        let _ = texture(i);
    }
}

