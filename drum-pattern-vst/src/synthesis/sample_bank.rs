/// One custom texture per LANE ([228]): the pool has one slot per track, and
/// a lane's Texture menu ends with that lane's own file.
pub const LANE_TEXTURE_SLOTS: usize = crate::track::MAX_TRACKS;
/// Index of the "Custom" entry in the Texture menu. It is FROZEN at 4: saved
/// lanes store the menu index, so a texture added later ([291], Pad) goes AFTER
/// Custom (menu index 5, bank 4) instead of shifting it.
pub const CUSTOM_TEXTURE_INDEX: usize = 4;
/// Menu entries that are not embedded banks: just Custom.
const MENU_ONLY_ENTRIES: usize = 1;
/// Entries in the Texture menu.
pub const TEXTURE_OPTION_COUNT: usize = TEXTURE_COUNT + MENU_ONLY_ENTRIES;

/// The embedded bank behind a Texture-menu index, `None` for Custom.
pub const fn embedded_bank_for_menu(menu_index: usize) -> Option<usize> {
    if menu_index < CUSTOM_TEXTURE_INDEX {
        Some(menu_index)
    } else if menu_index == CUSTOM_TEXTURE_INDEX {
        None
    } else {
        Some(menu_index - 1)
    }
}

/// The Texture-menu index of an embedded bank (inverse of the above).
#[cfg(test)]
pub const fn menu_index_of_bank(bank: usize) -> usize {
    if bank < CUSTOM_TEXTURE_INDEX {
        bank
    } else {
        bank + 1
    }
}
/// Longest custom texture kept, in seconds - 60 s at 48 kHz is 11.5 MB of f32
/// per lane, and the offset slider gets no more precise past that anyway.
pub const USER_TEXTURE_MAX_SECS: f32 = 60.0;

/// The per-instance pool of lane textures. The UI (or the state restore)
/// publishes decoded files; the audio thread reads a lane's slot with ONE
/// atomic load plus an `Arc` clone (`arc_swap`), no lock, no allocation.
///
/// Memory discipline: a replaced texture is parked in `previous` on the UI side
/// for one more generation, so the voice that may still be reading it never
/// holds the last reference - freeing on the audio thread is what that would
/// mean. It is freed on the NEXT publish into the same lane, on the UI thread.
///
/// [253] Voices also keep their OWN `Arc` for the length of a hit
/// (`OneShotVoice::source`, `RiftVoice::source`), which can outlive the pool's
/// one-generation parking (file replaced twice without an intervening hit).
/// Those references go to `retired`, a preallocated queue drained by the UI
/// thread (`drain_retired`), so the audio thread never frees a texture.
pub struct TexturePool {
    slots: [arc_swap::ArcSwapOption<TextureBank>; LANE_TEXTURE_SLOTS],
    previous: std::sync::Mutex<[Option<Arc<TextureBank>>; LANE_TEXTURE_SLOTS]>,
    retired: crossbeam::queue::ArrayQueue<Arc<TextureBank>>,
}

/// [253] How many replaced textures wait for the UI to free them. Full =
/// the UI is not draining (editor closed): the push fails and the texture is
/// dropped on the spot — a bounded, degraded case, never a leak or a panic.
pub const RETIRE_QUEUE_CAPACITY: usize = 64;

impl Default for TexturePool {
    fn default() -> Self {
        Self::new()
    }
}

impl TexturePool {
    pub fn new() -> Self {
        Self {
            slots: std::array::from_fn(|_| arc_swap::ArcSwapOption::from(None)),
            previous: std::sync::Mutex::new(std::array::from_fn(|_| None)),
            retired: crossbeam::queue::ArrayQueue::new(RETIRE_QUEUE_CAPACITY),
        }
    }

    /// UI / main thread only: install (or remove) a lane's texture.
    pub fn publish(&self, lane: usize, bank: Option<Arc<TextureBank>>) {
        if lane >= LANE_TEXTURE_SLOTS {
            return;
        }
        let old = self.slots[lane].swap(bank);
        if let Ok(mut previous) = self.previous.lock() {
            previous[lane] = old;
        }
        // [253] We are on a non-RT thread: free whatever the audio thread
        // retired since the last drain.
        self.drain_retired();
    }

    /// Audio thread: hand over a replaced texture instead of dropping it here.
    /// A hit may hold the LAST reference; freeing up to ~23 MB
    /// (`USER_TEXTURE_MAX_SECS` of stereo f32) in the callback is a dropout.
    /// Lock-free push into a preallocated queue; on a full queue the texture
    /// is dropped in place (bounded degraded case, see RETIRE_QUEUE_CAPACITY).
    pub fn retire(&self, bank: Arc<TextureBank>) {
        let _ = self.retired.push(bank);
    }

    /// UI / main thread: free every texture the audio thread retired. Called
    /// from `publish` and once per editor frame (`ui.rs`).
    pub fn drain_retired(&self) {
        while self.retired.pop().is_some() {}
    }

    #[cfg(test)]
    pub fn retired_len(&self) -> usize {
        self.retired.len()
    }

    /// Audio thread: the lane's texture, held alive by the returned `Arc`.
    pub fn get(&self, lane: usize) -> Option<Arc<TextureBank>> {
        self.slots.get(lane)?.load_full()
    }

    pub fn is_loaded(&self, lane: usize) -> bool {
        self.slots
            .get(lane)
            .map(|s| s.load().is_some())
            .unwrap_or(false)
    }
}

/// What a Rift voice reads during one hit: an embedded texture, or a user one
/// held alive for as long as the hit lasts.
pub enum TextureSource {
    Embedded(&'static TextureBank),
    User(Arc<TextureBank>),
}

impl TextureSource {
    pub fn bank(&self) -> &TextureBank {
        match self {
            TextureSource::Embedded(bank) => bank,
            TextureSource::User(bank) => bank,
        }
    }
}

/// Resolve a Texture-menu index for one lane: the embedded textures, or the
/// lane's own file ("Custom", `lane` = the pool and the lane's slot). A lane
/// with no file - never loaded, gone missing, unreadable - falls back to the
/// first embedded texture: a hit must never go silent for want of a file.
/// Out-of-range indices clamp into the menu.
pub fn resolve_texture(index: usize, lane: Option<(&TexturePool, usize)>) -> TextureSource {
    let index = index.min(TEXTURE_OPTION_COUNT - 1);
    if let Some(bank) = embedded_bank_for_menu(index) {
        return TextureSource::Embedded(texture(bank));
    }
    match lane.and_then(|(pool, slot)| pool.get(slot)) {
        Some(bank) => TextureSource::User(bank),
        None => TextureSource::Embedded(texture(0)),
    }
}

/// Decode a WAV file from disk into a texture: any integer depth or float,
/// capped at `USER_TEXTURE_MAX_SECS`. A stereo file keeps its two channels
/// (`data` = left, `right` = right) so Rift's Stereo switch can play them as
/// they are; more than two channels are averaged to mono. Never called on
/// the audio thread. Errors are for the UI to show.
pub fn load_texture_file(path: &std::path::Path) -> Result<TextureBank, String> {
    let mut reader = hound::WavReader::open(path).map_err(|e| e.to_string())?;
    let spec = reader.spec();
    let channels = spec.channels.max(1) as usize;
    if spec.sample_rate == 0 {
        return Err("sample rate of 0".to_string());
    }
    let max_frames = (USER_TEXTURE_MAX_SECS * spec.sample_rate as f32) as usize;
    let frames = (reader.len() as usize / channels).min(max_frames);

    // Interleaved samples as f32, whatever the file's format.
    let mut interleaved: Vec<f32> = Vec::with_capacity(frames * channels);
    match spec.sample_format {
        hound::SampleFormat::Float => {
            for sample in reader.samples::<f32>().take(frames * channels) {
                interleaved.push(sample.map_err(|e| e.to_string())?);
            }
        }
        hound::SampleFormat::Int => {
            let bits = spec.bits_per_sample.clamp(1, 32);
            let scale = 1.0 / (1u64 << (bits - 1)) as f32;
            for sample in reader.samples::<i32>().take(frames * channels) {
                interleaved.push(sample.map_err(|e| e.to_string())? as f32 * scale);
            }
        }
    }
    let frames = interleaved.len() / channels;
    if frames < 4 {
        return Err("no audio in the file".to_string());
    }

    let (data, right) = if channels == 2 {
        let left: Vec<f32> = interleaved.iter().step_by(2).copied().collect();
        let right: Vec<f32> = interleaved.iter().skip(1).step_by(2).copied().collect();
        (left, Some(right))
    } else {
        let inv = 1.0 / channels as f32;
        let mono: Vec<f32> = interleaved
            .chunks_exact(channels)
            .map(|frame| frame.iter().sum::<f32>() * inv)
            .collect();
        (mono, None)
    };
    // The picture is the mono mix, whatever the switch says.
    let peaks = match &right {
        Some(r) => {
            let mix: Vec<f32> = data.iter().zip(r).map(|(l, r)| 0.5 * (l + r)).collect();
            peak_summary(&mix)
        }
        None => peak_summary(&data),
    };
    Ok(TextureBank {
        source_rate: spec.sample_rate as f32,
        data,
        right,
        peaks,
    })
}

fn read_u16_le(bytes: &[u8], off: usize) -> Option<u16> {
    Some(u16::from_le_bytes([*bytes.get(off)?, *bytes.get(off + 1)?]))
}

fn read_u32_le(bytes: &[u8], off: usize) -> Option<u32> {
    Some(u32::from_le_bytes([
        *bytes.get(off)?,
        *bytes.get(off + 1)?,
        *bytes.get(off + 2)?,
        *bytes.get(off + 3)?,
    ]))
}

/// Decode an embedded RIFF/WAVE file to mono f32 samples plus its sample rate.
///
/// Handles the two formats we ship: IEEE float 32-bit and PCM 16-bit. On a
/// multi-channel file only the first channel is read. Anything else decodes to
/// an empty buffer — the voice then stays inert instead of panicking.
fn decode_wav(bytes: &[u8]) -> (f32, Vec<f32>) {
    let is_riff = bytes.len() >= 12 && &bytes[0..4] == b"RIFF" && &bytes[8..12] == b"WAVE";

    let mut source_rate = 44100u32;
    let mut audio_format = 3u16; // IEEE float
    let mut channels = 1u16;
    let mut bits_per_sample = 32u16;
    let mut data: Option<(usize, usize)> = None; // (offset, len)

    if is_riff {
        let mut pos = 12usize;
        while pos + 8 <= bytes.len() {
            let id = &bytes[pos..pos + 4];
            let size = read_u32_le(bytes, pos + 4).unwrap_or(0) as usize;
            let body = pos + 8;
            if body + size > bytes.len() {
                break;
            }
            match id {
                b"fmt " => {
                    audio_format = read_u16_le(bytes, body).unwrap_or(3);
                    channels = read_u16_le(bytes, body + 2).unwrap_or(1);
                    source_rate = read_u32_le(bytes, body + 4).unwrap_or(44100);
                    bits_per_sample = read_u16_le(bytes, body + 14).unwrap_or(32);
                }
                b"data" => {
                    data = Some((body, size));
                    break;
                }
                _ => {}
            }
            pos = body + size + (size & 1);
        }
    }

    let samples: Vec<f32> = match data {
        Some((off, len)) if audio_format == 3 && bits_per_sample == 32 => {
            let frame = 4 * channels.max(1) as usize;
            (0..len / frame)
                .map(|i| {
                    let o = off + i * frame;
                    f32::from_le_bytes([bytes[o], bytes[o + 1], bytes[o + 2], bytes[o + 3]])
                })
                .collect()
        }
        Some((off, len)) if audio_format == 1 && bits_per_sample == 16 => {
            let frame = 2 * channels.max(1) as usize;
            (0..len / frame)
                .map(|i| {
                    let o = off + i * frame;
                    i16::from_le_bytes([bytes[o], bytes[o + 1]]) as f32 / 32768.0
                })
                .collect()
        }
        // Unparseable file: fall back to silence so the voice stays inert
        // instead of panicking on host-supplied-adjacent data.
        _ => Vec::new(),
    };

    (source_rate as f32, samples)
}

fn load_bank(bytes: &[u8]) -> SampleBank {
    let (source_rate, samples) = decode_wav(bytes);
    let hit_len = samples.len() / HIT_COUNT;
    let hits: [Vec<f32>; HIT_COUNT] = std::array::from_fn(|h| {
        if hit_len == 0 {
            Vec::new()
        } else {
            samples[h * hit_len..(h + 1) * hit_len].to_vec()
        }
    });

    SampleBank { source_rate, hits }
}

